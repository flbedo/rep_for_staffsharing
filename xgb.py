import re
import numpy as np
import torch
from transformers import AutoTokenizer, AutoModel
from xgboost import XGBClassifier
from sklearn.preprocessing import LabelEncoder

class PredictionModel:
    def __init__(self, keywords, rules=None, model_path="cointegrated/rubert-tiny"):
        self.tokenizer = AutoTokenizer.from_pretrained(model_path)
        self.bert_model = AutoModel.from_pretrained(model_path)
        
        self.classes = list(keywords.keys())
        self.keywords = keywords
        self.rules = rules if rules else keywords
        
        self.label_encoder = LabelEncoder()
        self.label_encoder.fit(self.classes)
        
        # Явно указываем objective для многоклассовой классификации
        self.classifier = XGBClassifier(
            n_estimators=200, #кол-во решающих моделей принятия решений
            learning_rate=0.05, # влияние ошибок при обучении на итог
            max_depth=5, # кол-во проверок и группировок (ветвление вариантов)
            subsample=0.8, # доля данных для обучения
            colsample_bytree=0.7, # устойчивость к шуму признаков
            reg_lambda=1.0, # штраф за неустойчивость к шуму признака
            objective='multi:softmax',
            num_class=len(self.classes),
            eval_metric='merror'
        )

    def get_embeddings(self, text):
        """
        Генерация векторных представлений текста с помощью RuBERT
        """
        inputs = self.tokenizer(
            text, 
            return_tensors="pt", 
            padding=True, 
            truncation=True, 
            max_length=512
        )
        with torch.no_grad():
            outputs = self.bert_model(**inputs)
        return outputs.last_hidden_state[:, 0, :].numpy().flatten()

    def extract_manual_features(self, text):
        """
        Извлечение ручных признаков:
        - Бинарные флаги наличия ключевых слов по категориям
        - Дополнительные признаки текста
        """
        features = []

        # Добавление бинарных флагов для каждой категории
        for category in self.keywords:
            # Проверка наличия хотя бы одного ключевого слова в категории
            flag = 1 if any(kw in text.lower() for kw in self.keywords[category]) else 0
            features.append(flag)

        # Дополнительные признаки
        features.append(len(text))              # Длина текста
        features.append(1 if '?' in text else 0) # Наличие вопроса
        
        return np.array(features)

    def rule_based_check(self, text):
        """
        Правило-базированная классификация текста по заранее заданным паттернам.
        Возвращает метку класса, если найдено совпадение, иначе None.
        """
        text_lower = text.lower()


        patterns = self.rules
        # Проверка каждого паттерна
        for category, regex_list in patterns.items():
            if any(re.search(r, text_lower) for r in regex_list):
                return category

        return None


    def create_feature_vector(self, text):
        """
        Создание объединенного вектора признаков
        """
        embeddings = self.get_embeddings(text)
        manual_features = self.extract_manual_features(text)
        return np.concatenate((embeddings, manual_features))

    def predict(self, text):
        """
        Основной пайплайн классификации
        """
        # Применяем правило-базированную проверку
        rule_result = self.rule_based_check(text)
        if rule_result:
            return rule_result
        
        # Готовим признаки и делаем ML-предсказание
        feature_vector = self.create_feature_vector(text)
        prediction_idx = self.classifier.predict([feature_vector])[0]
        return self.label_encoder.inverse_transform([prediction_idx])[0]


    def train(self, texts, labels):
        encoded_labels = self.label_encoder.transform(labels)
        feature_vectors = [self.create_feature_vector(text) for text in texts]
        
        visual_test = (len(feature_vectors[0]) / len(feature_vectors[-1])) * 100
        
        self.classifier.fit(feature_vectors, encoded_labels)
        print(f"Размерность векторов признаков: {visual_test}% ({len(feature_vectors[0])})")
        
