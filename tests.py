import xgboost as xgb
import numpy as np

# Фактически, это просто умная сравнивалка по разным данным. Таким образом можно вбить разные параметры и не мучиться с коэфицентами!

# ДАННЫЕ: 2 поисковых запроса с результатами
# Запрос 1: "игры для PS5" - 3 игры
# Запрос 2: "фильмы про войну" - 2 фильма

# Признаки каждого элемента (рейтинг, отзывы, цена и т.д.)
X_train = np.array([
    [4.8, 1500],  # Игра 1 - высокий рейтинг, много отзывов
    [4.2, 800],   # Игра 2 - средний рейтинг
    [3.5, 300],   # Игра 3 - низкий рейтинг
    [4.7, 2000],  # Фильм 1 - высокий рейтинг
    [3.9, 60000]    # Фильм 2 - средний рейтинг
])

# Релевантность (чем выше - тем лучше должен быть ранг)
y_train = np.array([2, 1, 0, 2, 1])

# Размеры групп: 3 элемента в первой группе, 2 во второй
group_sizes = [3, 2]

# Тестовые данные (новые запросы)
X_test = np.array([
    [4.5, 1200],  # Новый элемент группы 1
    [4.0, 700],   # Новый элемент группы 1  
    [4.6, 1800],
    [3.9, 3000],
    [2.5, 120000],
    [5.0, 1],
    # Новый элемент группы 2
])
test_group_sizes = [3, 3]  # 2 в первой тестовой группе, 1 во второй

# Подготовка данных
dtrain = xgb.DMatrix(X_train, label=y_train, group=group_sizes)
dtest = xgb.DMatrix(X_test, group=test_group_sizes)

# Параметры модели
params = {
    'objective': 'rank:pairwise',  # Попарное сравнение
    'eta': 0.1,                    # Скорость обучения
    'gamma': 1.0,                  # Минимальное улучшение для разделения
    'eval_metric': 'ndcg'          # Метрика качества ранжирования
}

# Обучение модели
model = xgb.train(params, dtrain, num_boost_round=100)

# Предсказание
predictions = model.predict(dtest)
print("Предсказанные scores:", predictions)

# Интерпретация результатов:
# Для группы 1: [4.5, 1200] получит более высокий score чем [4.0, 700]
# Для группы 2: один элемент - будет на первом месте